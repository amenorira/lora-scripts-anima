def _show_if_one_of(key: str, values: Iterable[str]) -> dict[str, Any]:
    ordered = list(values)
    condition: dict[str, Any] = {"key": key, "eq": ordered[0]}
    if len(ordered) > 1:
        condition["_or"] = ordered[1:]
    return condition


